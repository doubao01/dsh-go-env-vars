/**
 * Shell bridge.
 *
 * The engine only accepts contributed variables in its managed `DSH_*`
 * namespace, so a stored `GITHUB_TOKEN` reaches a command as
 * `$DSH_VAR_GITHUB_TOKEN`. Tools like `gh`, `git` and `curl` read the plain
 * name instead.
 *
 * This module writes a small shell file that re-exports every variable under
 * its plain name, so sourcing it once makes those tools work unchanged:
 *
 * ```sh
 * . ~/.dsh/dsh-go/env.sh
 * gh auth status
 * ```
 *
 * The file is regenerated on every store write, so it never goes stale.
 * @module bridge
 */

import { mkdir, readFile, rename, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { homedir } from 'node:os'

import { PREFIX } from './names.js'

/** Absolute path of the generated shell file. */
export const BRIDGE_PATH = join(
  process.env.DSH_HOME?.trim() || join(homedir(), '.dsh'),
  'dsh-go',
  'env.sh',
)

/** The user's interactive shell startup file. */
export const BASHRC_PATH = join(homedir(), '.bashrc')

/**
 * Marker line identifying our block in `.bashrc`. Present means the block is
 * installed; the block is written between this marker and END_MARKER so a
 * later run can replace it in place instead of appending duplicates.
 */
const BEGIN_MARKER = '# >>> dsh-go-env-vars >>>'
const END_MARKER = '# <<< dsh-go-env-vars <<<' 

/**
 * Build the shell script body.
 *
 * Values are single-quoted with embedded quotes escaped, so a token
 * containing `$`, backticks or quotes cannot break out and execute.
 * @param {Record<string, { value: string }>} vars
 * @returns {string}
 */
export function renderBridge(vars) {
  const names = Object.keys(vars)
    .filter((name) => typeof vars[name]?.value === 'string' && vars[name].value !== '')
    .sort((a, b) => a.localeCompare(b))

  const lines = [
    '# Generated by dsh-go-env-vars — do not edit; rewritten on every change.',
    '#',
    '# The engine injects every variable as $DSH_VAR_<NAME>. Standard tools read',
    '# the plain <NAME>, so this file re-exports each one under that name.',
    '#',
    '# Load it once per shell:',
    '#   . ~/.dsh/dsh-go/env.sh',
    '# To load it in every interactive shell, add that line to ~/.bashrc.',
  ]

  if (names.length === 0) {
    lines.push('', '# No variables stored.')
  }

  for (const name of names) {
    const envName = `${PREFIX}${name}`
    lines.push(
      `if [ -n "\${${envName}:-}" ]; then`,
      `  export ${name}="\${${envName}}"`,
      'fi',
    )
  }

  return `${lines.join('\n')}\n`
}

/**
 * Write the bridge file for the current variables.
 * @param {Record<string, { value: string }>} vars
 * @returns {Promise<void>}
 */
export async function writeBridge(vars) {
  await mkdir(dirname(BRIDGE_PATH), { recursive: true })
  const tmp = `${BRIDGE_PATH}.tmp`
  await writeFile(tmp, renderBridge(vars), 'utf8')
  await rename(tmp, BRIDGE_PATH)
  // Keep the interactive-shell hook installed; no-op when already current.
  await writeBashrc()
}

/**
 * Build the `.bashrc` block that loads the bridge.
 * @returns {string}
 */
export function renderBashrcBlock() {
  return [
    BEGIN_MARKER,
    '# Loads the dsh-go environment bridge, so $DSH_VAR_<NAME> is also',
    '# available as $<NAME> for gh, git and SDKs. Rewritten by the plugin.',
    `[ -r "${BRIDGE_PATH}" ] && . "${BRIDGE_PATH}"`,
    END_MARKER,
  ].join('\n')
}

/**
 * Install or replace our block in `.bashrc`.
 *
 * Idempotent: an existing block between the markers is replaced in place, so
 * repeated saves never duplicate it. The rest of the file is left untouched.
 * A missing `.bashrc` is created.
 * @returns {Promise<void>}
 */
export async function writeBashrc() {
  let current = ''
  try {
    current = await readFile(BASHRC_PATH, 'utf8')
  } catch {
    // No .bashrc yet: start from empty so the block becomes the whole file.
  }

  const block = renderBashrcBlock()
  const begin = current.indexOf(BEGIN_MARKER)
  const end = current.indexOf(END_MARKER)

  let next
  if (begin >= 0 && end > begin) {
    // Replace the existing block, keeping the surrounding file as it was.
    next = current.slice(0, begin) + block + current.slice(end + END_MARKER.length)
  } else if (current === '') {
    next = `${block}\n`
  } else {
    next = `${current.replace(/\n*$/, '\n')}\n${block}\n`
  }

  if (next === current) return
  const tmp = `${BASHRC_PATH}.tmp`
  await writeFile(tmp, next, 'utf8')
  await rename(tmp, BASHRC_PATH)
}
